'''
Runs the EQ of an input device as a PipeWire filter chain in its own process, the way
pw-loopback runs a route. Its two streams are linked by hand and stay unlinked until then:

    device monitor -> input.nm_eq_<device> ~ biquads ~ output.nm_eq_<device> -> routes

The process outlives NeoMixer so audio keeps its EQ with the window closed, and the next
run finds it again by its config path.
'''
import os
import re
import hashlib
import logging
import signal
import subprocess
import time

from neomixer.model.eq_model import FILTER_LABELS
from neomixer.scripts import pmctl
from neomixer.settings import RUNTIME_DIR

LOG = logging.getLogger('generic')

PREAMP = 'pre'
# Above Nyquist, where PipeWire's lowpass passes everything through
OPEN_LOWPASS_FREQ = 96000.0


def _safe_name(device_name: str) -> str:
    return re.sub(r'[^a-zA-Z0-9._-]', '_', device_name)


def eq_nodes(device_name: str) -> tuple[str, str]:
    '''Returns the node names of a device's EQ streams, as (capture, playback).'''
    safe = _safe_name(device_name)
    return f'input.nm_eq_{safe}', f'output.nm_eq_{safe}'


def config_path(device_name: str) -> str:
    return os.path.join(RUNTIME_DIR, f'eq-{_safe_name(device_name)}.conf')


def signature(positions: list[str], eq) -> str:
    '''
    Hash of what the filter chain cannot change while running: its channels and filter types.
    Anything else is a runtime parameter.
    '''
    types = ','.join(band.type for band in eq.bands)
    return hashlib.sha1(f"{' '.join(positions)}|{types}".encode()).hexdigest()[:12]


def build_config(device_name: str, positions: list[str], eq) -> str:
    '''Returns the config of the PipeWire process that hosts a device's EQ.'''
    capture, playback = eq_nodes(device_name)
    values = dict(band_params(eq))

    nodes = []
    names = []
    for index, band in enumerate(eq.bands):
        name = f'b{index + 1}'
        names.append(name)
        nodes.append(
            f'{{ type = builtin name = {name} label = {FILTER_LABELS[band.type]} control = {{ '
            f'Freq = {values[f"{name}:Freq"]:.3f} Q = {values[f"{name}:Q"]:.3f} Gain = {values[f"{name}:Gain"]:.3f} }} }}'
        )

    # A high shelf at 0 Hz is a plain gain
    names.append(PREAMP)
    nodes.append(
        f'{{ type = builtin name = {PREAMP} label = bq_highshelf control = {{ '
        f'Freq = 0.0 Q = 1.0 Gain = {values[f"{PREAMP}:Gain"]:.3f} }} }}'
    )
    links = ' '.join(
        f'{{ output = "{source}:Out" input = "{target}:In" }}' for source, target in zip(names, names[1:])
    )

    # Passive: the EQ never keeps a sound card awake by itself. Virtual: hidden from volume applets.
    stream_props = (
        'node.autoconnect = false node.dont-reconnect = true node.passive = true node.virtual = true '
        'stream.dont-remix = true media.category = Filter'
    )
    position_list = ' '.join(positions)
    return f'''# Generated by NeoMixer
context.properties = {{ log.level = 2 }}
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
    {{ name = libpipewire-module-rt args = {{ nice.level = -11 }} flags = [ ifexists nofail ] }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-adapter }}
    {{ name = libpipewire-module-filter-chain
        args = {{
            node.description = "NeoMixer EQ {device_name}"
            media.name = "NeoMixer EQ {device_name}"
            filter.graph = {{
                nodes = [
                    {chr(10).join(nodes)}
                ]
                links = [ {links} ]
            }}
            audio.channels = {len(positions)}
            audio.position = [ {position_list} ]
            capture.props = {{ node.name = "{capture}" neomixer.eq.signature = "{signature(positions, eq)}" {stream_props} }}
            playback.props = {{ node.name = "{playback}" {stream_props} }}
        }}
    }}
]
'''


def band_params(eq) -> list[tuple[str, float]]:
    '''
    Returns the runtime parameters of an EQ as (name, value) pairs. A disabled EQ or band
    keeps running with parameters that make its filter pass everything through.
    '''
    params = []
    for index, band in enumerate(eq.bands):
        name = f'b{index + 1}'
        freq, gain = band.freq, band.gain
        if not eq.enabled or not band.enabled:
            gain = 0.0
            if band.type == 'lowpass':
                freq = OPEN_LOWPASS_FREQ
            elif band.type in ('highpass', 'notch'):
                freq = 0.0

        params += [(f'{name}:Freq', float(freq)), (f'{name}:Q', float(band.q)), (f'{name}:Gain', float(gain))]

    params.append((f'{PREAMP}:Gain', float(eq.preamp) if eq.enabled else 0.0))
    return params


def set_params(device_name: str, eq) -> bool:
    '''Update a running EQ without interrupting its audio.'''
    capture, _ = eq_nodes(device_name)
    values = ' '.join(f'"{name}" {value:.3f}' for name, value in band_params(eq))
    ret = subprocess.run(
        ['pw-cli', 'set-param', capture, 'Props', f'{{ params = [ {values} ] }}'],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False
    ).returncode
    if ret != 0:
        LOG.warning('Failed to update the EQ of %s', device_name)
    return ret == 0


def start(device_name: str, positions: list[str], eq) -> subprocess.Popen:
    '''Write a device's EQ config and start its process.'''
    os.makedirs(RUNTIME_DIR, exist_ok=True)
    path = config_path(device_name)
    with open(path, 'w', encoding='utf-8') as config:
        config.write(build_config(device_name, positions, eq))

    LOG.debug('Starting EQ for %s: %s', device_name, path)
    # its own session: it must survive the terminal or window NeoMixer was started from
    return subprocess.Popen(
        ['pipewire', '-c', path], stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        start_new_session=True
    )


def wait_ready(device_name: str, channels: int, timeout: float = 3.0, interval: float = 0.02) -> bool:
    '''Poll until both streams of a device's EQ have a port per channel.'''
    capture, playback = eq_nodes(device_name)
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        try:
            if (len(pmctl.get_ports('input', capture)) >= channels
                    and len(pmctl.get_ports('output', playback)) >= channels):
                return True
        except RuntimeError:
            pass
        time.sleep(interval)
    return False


def running_pids(device_name: str) -> list[int]:
    '''Find the processes running a device's EQ, ours or from an earlier run.'''
    path = config_path(device_name).encode()
    pids = []
    for entry in os.listdir('/proc'):
        if not entry.isdigit():
            continue
        try:
            with open(f'/proc/{entry}/cmdline', 'rb') as cmdline:
                argv = cmdline.read().split(b'\0')
        except OSError:
            continue
        if argv[0].endswith(b'pipewire') and path in argv:
            pids.append(int(entry))
    return pids


def running_signature(device_name: str) -> str | None:
    '''Returns the signature an EQ from an earlier run was started with, None without a process.'''
    if not running_pids(device_name):
        return None
    try:
        with open(config_path(device_name), encoding='utf-8') as config:
            match = re.search(r'neomixer\.eq\.signature = "(\w+)"', config.read())
    except OSError:
        return None
    return match.group(1) if match else None


def stop(device_name: str, proc: subprocess.Popen | None = None):
    '''Stop every process running a device's EQ.'''
    if proc is not None and proc.poll() is None:
        proc.terminate()
        try:
            proc.wait(timeout=2)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()

    for pid in running_pids(device_name):
        try:
            os.kill(pid, signal.SIGTERM)
        except OSError:
            pass

    try:
        os.remove(config_path(device_name))
    except OSError:
        pass
