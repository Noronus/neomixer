'''
Runs a phone's audio as two PipeWire devices in a process of its own, the way pw_eq runs an EQ:

    routes -> neomixer_phone      ~ RTP over UDP ~> the phone's speaker
    routes <- neomixer_phone_mic  <~ RTP over UDP ~ the phone's microphone

Both are plain 16 bit PCM in RTP, which PipeWire's own modules send and receive: the source
keeps a jitter buffer and follows the phone's clock. The devices exist while a phone has its
audio switched on, to the mixer that is a headset being plugged in and pulled out.

Unlike an EQ this process must not outlive NeoMixer: nothing else would ever stop it sending.
'''
import os
import re
import logging
import signal
import subprocess

from neomixer.settings import RUNTIME_DIR

LOG = logging.getLogger('generic')

SINK_NAME = 'neomixer_phone'
SOURCE_NAME = 'neomixer_phone_mic'
NODE_NAMES = (SINK_NAME, SOURCE_NAME)

RATE = 48000
SINK_CHANNELS = 2
SOURCE_CHANNELS = 1
# One packet of the phone's microphone, the source's buffer has to be a multiple of it
PACKET_MS = 5
# What the source keeps buffered against the jitter of a wireless network
MIC_LATENCY_MS = 40
PAYLOAD_TYPE = 127


def config_path() -> str:
    return os.path.join(RUNTIME_DIR, 'phone.conf')


def log_path() -> str:
    return os.path.join(RUNTIME_DIR, 'phone.log')


def _quoted(text: str) -> str:
    '''A name as it can stand between quotes in a PipeWire config.'''
    return re.sub(r'[^\w .()+-]', '', text).strip() or 'Phone'


def build_config(phone_ip: str, phone_port: int, mic_port: int, phone_name: str) -> str:
    '''
    Returns the config of the PipeWire process that hosts a phone's two devices.
        "phone_ip" and "phone_port" are where the phone listens for what it plays
        "mic_port" is the local port its microphone arrives on
    '''
    name = _quoted(phone_name)
    return f'''# Generated by NeoMixer
context.properties = {{ log.level = 2 }}
context.spa-libs = {{
    audio.convert.* = audioconvert/libspa-audioconvert
    support.*       = support/libspa-support
}}
context.modules = [
    {{ name = libpipewire-module-rt args = {{ nice.level = -11 }} flags = [ ifexists nofail ] }}
    {{ name = libpipewire-module-protocol-native }}
    {{ name = libpipewire-module-client-node }}
    {{ name = libpipewire-module-adapter }}
    {{ name = libpipewire-module-rtp-sink
        args = {{
            destination.ip = "{phone_ip}"
            destination.port = {int(phone_port)}
            net.mtu = 1280
            sess.min-ptime = 2
            sess.max-ptime = {PACKET_MS}
            sess.name = "NeoMixer"
            sess.media = "audio"
            rtp.payload = {PAYLOAD_TYPE}
            audio.format = "S16BE"
            audio.rate = {RATE}
            audio.channels = {SINK_CHANNELS}
            audio.position = [ FL FR ]
            stream.props = {{
                node.name = "{SINK_NAME}"
                node.description = "{name}"
                media.class = "Audio/Sink"
            }}
        }}
    }}
    {{ name = libpipewire-module-rtp-source
        args = {{
            source.ip = "0.0.0.0"
            source.port = {int(mic_port)}
            sess.latency.msec = {MIC_LATENCY_MS}
            sess.ignore-ssrc = true
            sess.media = "audio"
            sess.min-ptime = {PACKET_MS}
            sess.max-ptime = {PACKET_MS}
            rtp.payload = {PAYLOAD_TYPE}
            audio.format = "S16BE"
            audio.rate = {RATE}
            audio.channels = {SOURCE_CHANNELS}
            audio.position = [ MONO ]
            stream.props = {{
                node.name = "{SOURCE_NAME}"
                node.description = "{name} microphone"
                media.class = "Audio/Source"
            }}
        }}
    }}
]
'''


def start(phone_ip: str, phone_port: int, mic_port: int, phone_name: str) -> subprocess.Popen:
    '''Write the config and start the process, in place of any that is running.'''
    stop()
    os.makedirs(RUNTIME_DIR, exist_ok=True)
    path = config_path()
    with open(path, 'w', encoding='utf-8') as config:
        config.write(build_config(phone_ip, phone_port, mic_port, phone_name))

    LOG.debug('Starting phone audio for %s:%s', phone_ip, phone_port)
    with open(log_path(), 'wb') as log:
        return subprocess.Popen(['pipewire', '-c', path], stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=log)


def last_error() -> str:
    '''What the process last said, for when it did not start.'''
    try:
        with open(log_path(), encoding='utf-8', errors='replace') as log:
            lines = [line.strip() for line in log if line.strip()]
    except OSError:
        return ''
    return lines[-1] if lines else ''


def running_pids() -> list[int]:
    '''Find the processes running phone audio, ours or left by a run that did not get to stop it.'''
    path = config_path().encode()
    pids = []
    for entry in os.listdir('/proc'):
        if not entry.isdigit():
            continue
        try:
            with open(f'/proc/{entry}/cmdline', 'rb') as cmdline:
                argv = cmdline.read().split(b'\0')
        except OSError:
            continue
        if argv[0].endswith(b'pipewire') and path in argv:
            pids.append(int(entry))
    return pids


def stop(proc: subprocess.Popen | None = None):
    '''Stop every process running phone audio.'''
    if proc is not None and proc.poll() is None:
        proc.terminate()
        try:
            proc.wait(timeout=2)
        except subprocess.TimeoutExpired:
            proc.kill()
            proc.wait()

    for pid in running_pids():
        try:
            os.kill(pid, signal.SIGTERM)
        except OSError:
            pass

    try:
        os.remove(config_path())
    except OSError:
        pass
